#include "Map.h"

Map::Map() {
    LoadMap();
}

void Map::LoadMap() {
    // Peta contoh dengan dinding '#' dan pellet '.'
    char temp[ROWS][COLS] = {
        {'#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#'},
        {'#','.','.','.','.','#','.','.','.','.','.','.','.','.','#','.','.','.','.','#'},
        {'#','.','#','#','.','#','.','#','#','#','#','#','#','.','#','.','#','#','.','#'},
        {'#','.','#','.','.','.','.','.','.','.','.','.','.','.','.','.','.','#','.','#'},
        {'#','.','#','.','#','#','.','#','#','.','.','#','#','.','#','#','.','#','.','#'},
        {'#','.','.','.','.','.','.','#','.','.','.','.','#','.','.','.','.','.','.','#'},
        {'#','.','#','.','#','#','.','#','#','#','#','#','#','.','#','#','.','#','.','#'},
        {'#','.','#','.','.','.','.','.','.','.','.','.','.','.','.','.','.','#','.','#'},
        {'#','.','#','#','.','#','.','#','#','#','#','#','#','.','#','.','#','#','.','#'},
        {'#','.','.','.','.','#','.','.','.','.','.','.','.','.','#','.','.','.','.','#'},
        {'#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#'}
    };

    for (int i = 0; i < ROWS; i++)
        for (int j = 0; j < COLS; j++)
            grid[i][j] = temp[i][j];
}

bool Map::IsWalkable(int x, int y) const {
    if (x < 0 || x >= COLS || y < 0 || y >= ROWS)
        return false;
    return grid[y][x] != '#';
}
